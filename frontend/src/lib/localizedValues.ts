export function optionLabel(language: Language, value: string): string {
  return Object.hasOwn(optionKeys, value) ? translate(language, optionKeys[value]) : value;
}
export function noticeMessage(language: Language, value: string): string {
  return Object.hasOwn(noticeKeys, value) ? translate(language, noticeKeys[value]) : value;
}
